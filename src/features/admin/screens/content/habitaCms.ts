export const IMAGE_SLOTS=["category.house","category.apt","category.villa","category.land","category.commercial","place.0","place.1","place.2","place.3","place.4","place.5"] as const;
export type HomeCopy=Record<string,string>;
export type HomePayload={v:1;copy:HomeCopy;images:Record<string,string>};
export const emptyHome=():HomePayload=>({v:1,copy:{...DEFAULT_COPY},images:{}});
const obj=(v:unknown):v is Record<string,unknown>=>!!v&&typeof v==='object'&&!Array.isArray(v);
const tokens=(s:string)=>[...s.matchAll(/\{([a-z]+)\}/g)].map(m=>m[1]).sort().join('|');
export function validCopy(key:string,value:unknown):value is string{return Object.prototype.hasOwnProperty.call(DEFAULT_COPY,key)&&typeof value==='string'&&value.trim().length>0&&value.length<=Math.max(220,key.length*3)&&tokens(key)===tokens(value);}
export function validImage(slot:string,value:unknown):value is string{return (IMAGE_SLOTS as readonly string[]).includes(slot)&&typeof value==='string'&&/^habita\.home\.[a-zA-Z0-9._-]{1,160}$/.test(value);}
export function mergeHome(raw:unknown,base=emptyHome()):HomePayload{const result:HomePayload={v:1,copy:{...base.copy},images:{...base.images}};if(!obj(raw)||raw.v!==1)return result;if(obj(raw.copy))for(const [k,v] of Object.entries(raw.copy))if(validCopy(k,v))result.copy[k]=v;if(obj(raw.images))for(const [k,v] of Object.entries(raw.images))if(validImage(k,v))result.images[k]=v;return result;}
export function validateHome(raw:unknown):string[]{if(!obj(raw)||raw.v!==1||!obj(raw.copy)||!obj(raw.images))return ['Invalid homepage payload'];const errors:string[]=[];for(const [k,v] of Object.entries(raw.copy))if(!validCopy(k,v))errors.push('Invalid copy: '+k);for(const [k,v] of Object.entries(raw.images))if(!validImage(k,v))errors.push('Invalid image: '+k);return errors;}
export function translate(copy:HomeCopy,key:string,values:Record<string,string|number>={}):string{return (copy[key]??DEFAULT_COPY[key]??key).replace(/\{([a-z]+)\}/g,(all,k)=>String(values[k]??all));}
